export const translations: Record<LanguageCode, TranslationDictionary> = new Proxy(rawTranslations, {
  get(target, prop: string) {
    const langKey = prop as LanguageCode;
    const requested = target[langKey] || target.en || {};
    const fallback = target.en || {};
    return new Proxy(requested, {
      get(t, key: string) {
        return (t as any)[key] !== undefined ? (t as any)[key] : (fallback as any)[key];
      },
    });
  },
}) as Record<LanguageCode, TranslationDictionary>;
